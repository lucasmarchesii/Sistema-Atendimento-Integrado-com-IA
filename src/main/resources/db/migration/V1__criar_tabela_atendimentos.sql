CREATE TABLE atendimentos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cliente      VARCHAR(255)  NOT NULL,
    mensagem          VARCHAR(2000) NOT NULL,
    status            VARCHAR(30)   NOT NULL,
    categoria         VARCHAR(30),
    prioridade        VARCHAR(30),
    assunto           VARCHAR(255),
    resposta_sugerida VARCHAR(2000),
    criado_em         TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT ck_atendimentos_status
        CHECK (status IN ('RECEBIDO', 'CLASSIFICADO', 'PENDENTE_CLASSIFICACAO')),
    CONSTRAINT ck_atendimentos_categoria
        CHECK (categoria IS NULL OR categoria IN ('FINANCEIRO', 'ACESSO', 'CANCELAMENTO', 'TECNICO', 'OUTROS')),
    CONSTRAINT ck_atendimentos_prioridade
        CHECK (prioridade IS NULL OR prioridade IN ('BAIXA', 'MEDIA', 'ALTA'))
);

CREATE INDEX idx_atendimentos_status_criado_em ON atendimentos (status, criado_em);